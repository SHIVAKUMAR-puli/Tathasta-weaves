'use client';

import { useEffect, useRef } from 'react';
import { buildPalette, drawWeave, hash } from '@/lib/weave';

const W = 520, H = 600;
const PROMPT = 'indigo hills at dusk';

// Draws the pattern offscreen, then reveals it row by row like cloth coming off a loom.
export default function HeroLoom() {
  const ref = useRef(null);

  useEffect(() => {
    const ctx = ref.current.getContext('2d');
    const off = document.createElement('canvas');
    off.width = W; off.height = H;
    const { colors } = buildPalette(PROMPT, 0);
    drawWeave(off.getContext('2d'), W, H, { colors, weave: 'twill', cell: 12, seed: hash(PROMPT) });

    if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
      ctx.drawImage(off, 0, 0);
      return;
    }
    let y = 0, frame;
    const step = () => {
      y = Math.min(y + 6, H);
      ctx.drawImage(off, 0, 0, W, y, 0, 0, W, y);
      if (y < H) frame = requestAnimationFrame(step);
    };
    frame = requestAnimationFrame(step);
    return () => cancelAnimationFrame(frame);
  }, []);

  return (
    <figure className="loom">
      <div className="loom-frame">
        <canvas ref={ref} width={W} height={H} aria-label="A twill pattern generated by Loom Studio" />
        <span className="ai-badge">AI generated</span>
      </div>
      <figcaption>Fig. 1. 3/1 twill, designed by our AI from the prompt &ldquo;{PROMPT}&rdquo;</figcaption>
    </figure>
  );
}
